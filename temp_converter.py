def c_to_f(c):
    """Конвертирует Цельсий в Фаренгейт."""
    return c * 9/5 + 32


def f_to_c(f):
    """Конвертирует Фаренгейт в Цельсий."""
    return (f - 32) * 5/9


def c_to_k(c):
    """Конвертирует Цельсий в Кельвин.
    
    Выбрасывает ValueError, если c < -273.15.
    """
    if c < -273.15:
        raise ValueError("Температура не может быть ниже абсолютного нуля (-273.15°C)")
    return c + 273.15
